const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises'), os = require('node:os'), path = require('node:path')
const { _electron, expect } = require('@playwright/test')
const root = path.resolve(__dirname, '..')

async function verifyReasoningDefault({ screenshots = process.env.DW_REASONING_SCREENSHOTS, onWindow } = {}) {
  const home = await fs.mkdtemp(path.join(os.tmpdir(), 'dw-reasoning-default-ui-'))
  let app, page
  const profile = () => page.evaluate(async () => { const snapshot = (await window.ds.providerSnapshot()).data; return snapshot.profiles.find(item => item.id === (snapshot.bindings.draftProfileId ?? snapshot.bindings.defaultProfileId)) })
  const open = async () => { await page.getByTestId('model-reasoning-trigger').click(); await page.getByRole('slider', { name: '思考强度', exact: true }).waitFor() }
  const slider = () => page.getByRole('slider', { name: '思考强度', exact: true })
  const shot = async name => { if (screenshots) await page.screenshot({ path: path.join(screenshots, name + '.png'), animations: 'disabled', scale: 'css' }) }
  try {
    await fs.writeFile(path.join(home, 'settings.json'), JSON.stringify({ workDir: home, docDir: home }))
    app = await _electron.launch({ args: [path.join(root, process.env.DW_UI_BUILD_DIR || 'out', 'main/index.js'), '--user-data-dir=' + home], env: { ...process.env, DEEPWRITER_API_KEY: '', NODE_ENV: 'test', DW_TEST_MODE: '1', DW_TEST_USERDATA: home } })
    page = await app.firstWindow(); page.setDefaultTimeout(12000); onWindow?.(app, page)
    await page.getByRole('textbox', { name: '任务内容' }).waitFor()
    await open(); await expect(slider()).toHaveAttribute('aria-valuetext', '默认'); await expect(slider()).toHaveValue('0')
    assert.deepEqual((await profile()).reasoning, { mode: 'default', effort: null, budgetTokens: null })
    await shot('reasoning-default')
    await slider().focus(); await page.keyboard.press('End')
    await expect.poll(async () => (await profile()).reasoning.effort).toBe('max')
    await expect(slider()).toHaveAttribute('aria-valuetext', '最高')
    await page.keyboard.press('Escape'); await page.reload(); await page.getByRole('textbox', { name: '任务内容' }).waitFor()
    await open(); await expect(slider()).toHaveAttribute('aria-valuetext', '最高')
    await shot('reasoning-explicit-max')
    await slider().focus(); await page.keyboard.press('Home')
    await expect.poll(async () => (await profile()).reasoning.mode).toBe('default')
    assert.deepEqual((await profile()).reasoning, { mode: 'default', effort: null, budgetTokens: null })
    await expect(slider()).toHaveAttribute('aria-valuetext', '默认')
    await slider().focus(); await page.keyboard.press('ArrowRight')
    await expect.poll(async () => (await profile()).reasoning.mode).toBe('disabled')
    await expect(slider()).toHaveAttribute('aria-valuetext', '思考关')
    await shot('reasoning-explicit-off')
    await page.keyboard.press('Escape'); await page.reload(); await page.getByRole('textbox', { name: '任务内容' }).waitFor()
    await open(); await expect(slider()).toHaveAttribute('aria-valuetext', '思考关')
    await slider().focus(); await page.keyboard.press('Home')
    await expect.poll(async () => (await profile()).reasoning.mode).toBe('default')
    await page.keyboard.press('Escape'); await page.reload(); await page.getByRole('textbox', { name: '任务内容' }).waitFor()
    await open(); await expect(slider()).toHaveAttribute('aria-valuetext', '默认')
    const fit = await page.getByTestId('model-reasoning-panel').evaluate(element => { const rect = element.getBoundingClientRect(); return rect.x >= 0 && rect.right <= innerWidth && rect.y >= 0 && rect.bottom <= innerHeight && element.scrollWidth <= element.clientWidth })
    assert(fit)
    await page.keyboard.press('Escape')
    const budgetModel = await page.evaluate(async () => {
      const result = await window.ds.providerCreateSetup({ displayName: '本机预算模型', baseUrl: 'http://127.0.0.1:48321/v1', apiKey: '', protocol: 'anthropic-messages', modelIds: ['claude-sonnet-4-5'] })
      if (!result.ok) throw new Error(result.error.message)
      const snapshot = (await window.ds.providerSnapshot()).data
      return snapshot.models.find(model => model.providerId === result.data.id)
    })
    assert.ok(budgetModel.capabilities.reasoning.budget)
    await page.locator('.dw-topbar').getByRole('button', { name: '设置', exact: true }).click()
    await page.getByRole('navigation', { name: '模型供应商' }).getByRole('button', { name: '本机预算模型', exact: true }).click()
    await page.locator('.dw-provider-advanced > summary').click()
    await page.getByRole('button', { name: 'Profile 模型', exact: true }).click()
    await page.getByRole('option').filter({ hasText: budgetModel.displayName }).click()
    await page.getByRole('button', { name: 'Profile 推理模式', exact: true }).click()
    await page.getByRole('option', { name: /^开启思考/ }).click()
    await expect(page.getByRole('button', { name: 'Profile 推理强度', exact: true })).toHaveCount(0)
    await page.getByRole('spinbutton', { name: '推理 token 预算', exact: true }).fill('4096')
    await page.getByLabel('最大输出', { exact: true }).fill('8192')
    await page.getByRole('button', { name: '保存并用于新任务', exact: true }).click()
    await expect.poll(async () => (await profile()).reasoning.budgetTokens).toBe(4096)
    assert.deepEqual((await profile()).reasoning, { mode: 'enabled', effort: null, budgetTokens: 4096 })
    await shot('reasoning-explicit-budget')
    await page.getByRole('button', { name: '关闭设置', exact: true }).click()
    await page.reload(); await page.getByRole('textbox', { name: '任务内容' }).waitFor()
    assert.deepEqual((await profile()).reasoning, { mode: 'enabled', effort: null, budgetTokens: 4096 })
  } finally {
    if (app) await app.close().catch(() => {})
    assert.equal(path.dirname(home), os.tmpdir()); assert(path.basename(home).startsWith('dw-reasoning-default-ui-'))
    await fs.rm(home, { recursive: true, force: true, maxRetries: 3, retryDelay: 100 })
  }
}
module.exports = { verifyReasoningDefault }
if (require.main === module) test('desktop model reasoning follows model by default, saves explicit choices and resets without disabling thinking', { timeout: 60000 }, verifyReasoningDefault)
