async function resize(app, width, height = 900) {
  await app.evaluate(({ BrowserWindow }, size) => {
    const win = BrowserWindow.getAllWindows().find(item => !item.webContents.getURL().includes('window=float'))
    if (win.isMaximized()) win.unmaximize()
    win.setContentSize(size.width, size.height)
  }, { width, height })
}
async function inViewport(page, selector) {
  const box = await page.locator(selector).boundingBox()
  const viewport = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }))
  assert.ok(box && box.x >= 0 && box.y >= 0 && box.x + box.width <= viewport.width + 1 && box.y + box.height <= viewport.height + 1, `${selector} is outside the viewport`)
}
