'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const { spawnSync } = require('node:child_process')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')

test('CLI reads the shipped story without a profile; choices and errors survive the JSON interface', async t => {
  const work = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'dw-routes-'))
  t.after(() => fs.rmSync(work, { recursive: true, force: true }))
  const cli = path.join(work, 'cli.cjs')
  const { buildCli } = await import('../src/cli/build.mjs')
  await buildCli({ outfile: cli })
  const call = (...args) => spawnSync(process.execPath, [cli, 'galgame', 'routes', ...args], { cwd: work, encoding:'utf8', env:{ ...process.env, DEEPWRITER_API_KEY: '' } })
  const sample = path.join(root, 'examples/last-ferry')
  const good = call(sample, '--json')
  assert.equal(good.status, 0, good.stderr)
  const { data } = JSON.parse(good.stdout)
  assert.deepEqual(data.edges.filter(e => e.type === 'menu').map(e => [e.choice, e.to]), [['敲铃应他','bells'], ['把票送过河','ticket']])
  assert.ok(data.labels.every(x => !path.isAbsolute(x.file) && x.line > 0))
  assert.deepEqual(data.diagnostics, [])
  const localized = path.join(work, 'localized')
  fs.mkdirSync(localized)
  fs.writeFileSync(path.join(localized, 'start.rpy'), 'label start:\n    jump 河岸.等候\n')
  fs.writeFileSync(path.join(localized, 'shore.rpy'), 'label 河岸:\n    jump .等候\nlabel .等候:\n    menu:\n        "敲铃":\n            jump .离岸\nlabel .离岸:\n    return\n')
  const scoped = call(localized, '--json')
  assert.equal(scoped.status, 0, scoped.stdout + scoped.stderr)
  const routes = JSON.parse(scoped.stdout).data
  assert.deepEqual(routes.labels.map(x => x.name).sort(), ['start','河岸','河岸.等候','河岸.离岸'].sort())
  assert.deepEqual(routes.edges.map(e => [e.from, e.to]).sort(), [['start','河岸.等候'],['河岸','河岸.等候'],['河岸.等候','河岸.离岸']].sort())
  const damaged = path.join(work,'changed');fs.mkdirSync(damaged);fs.writeFileSync(path.join(damaged,'script.rpy'), 'label start:\n  menu:\n    "走小路" if raining:\n      jump missing\n    "回家":\n      jump expression next_scene\n')
  const bad = call(damaged,'--json');assert.equal(bad.status,1)
  const report=JSON.parse(bad.stdout).data;assert.equal(report.edges[0].choice,'走小路')
  assert.deepEqual(report.diagnostics.filter(d=>d.severity==='error').map(d=>d.code),['missing-label'])
  assert.equal(call(path.join(work,'absent')).status,1)
  assert.equal(fs.existsSync(path.join(work,'.deepwriter-cli')), false)
})
